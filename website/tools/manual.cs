// Writes src/app/manual/engine-params.generated.ts: every block the engine registers with every parameter it has (id,
// name, kind, range, default, unit, taper, editor page, choices, and the Circuit Amp's name for a control on each
// model), so the manual's block reference lists exactly the knobs the app shows. Only what a knob does is written by
// hand, in src/app/manual/blocks/. Run from website/: `pnpm manual`.

using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using Cathode.Dsp;
using Cathode.Dsp.Native;
using Cathode.Dsp.Parameters;

var registry = BlockRegistry.CreateDefault().AddNativeBlocks();

static string KindOf(ParamKind kind) =>
    kind switch {
        ParamKind.Enum => "choice",
        ParamKind.Bool => "switch",
        _ => "float"
    };

var blocks = registry.Descriptors.Select(static d => new {
    typeId = d.TypeId,
    name = d.Name,
    category = d.Category,
    channels = d.Channels,
    maxInstances = d.MaxInstances,
    pages = d.Pages.Count > 0 ? d.Pages : null,
    typeResets = d.TypeResets.Count > 0 ? d.TypeResets : null,
    @params = d.Params.Select(static p => new {
        id = p.Id,
        name = p.Name,
        kind = KindOf(p.Kind),
        min = p.Min,
        max = p.Max,
        @default = p.Default,
        unit = p.Unit.Length > 0 ? p.Unit : null,
        taper = p.Taper == ParamTaper.Log ? "log" : null,
        page = p.Page,
        options = p.Options,
        typeLabels = p.TypeLabels
    })
});

var json = JsonSerializer.Serialize(
    blocks,
    new JsonSerializerOptions {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
    }
);
var path = Path.Combine("src", "app", "manual", "engine-params.generated.ts");

Directory.CreateDirectory(Path.GetDirectoryName(path)!);
File.WriteAllText(
    path,
    "// Generated by tools/manual.cs from the engine's block registry: run `pnpm manual`, do not edit.\n\n" +
    "import type { EngineBlock } from './engine';\n\n" +
    $"export const ENGINE_BLOCKS: readonly EngineBlock[] = {json};\n"
);
Console.WriteLine($"Wrote {path}");
