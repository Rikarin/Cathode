// Writes src/app/catalog/engine.generated.ts: every block type the engine registers with its Type choices, the drive
// and wah circuits with what each is modelled after, and the Cab block's speakers, microphones and cabinets. Read from
// the engine itself, so the catalogue page lists exactly what Cathode has. Run from website/: `pnpm catalog`.

using System.Text.Encodings.Web;
using System.Text.Json;
using Cathode.Dsp;
using Cathode.Dsp.Blocks;
using Cathode.Dsp.Native;
using Cathode.Dsp.Parameters;

var registry = BlockRegistry.CreateDefault().AddNativeBlocks();
var cab = registry.Descriptors.Single(static d => d.TypeId == "cab");

string[] OptionsOf(BlockDescriptor block, string id) =>
    [..block.Params.FirstOrDefault(p => p.Id == id && p.Options is not null)?.Options ?? []];

var catalogue = new {
    blocks = registry.Descriptors.Select(d => new {
        typeId = d.TypeId,
        name = d.Name,
        category = d.Category,
        types = OptionsOf(d, "type")
    }),
    drives = DriveCircuits.All.Select(static c => new { name = c.Name, modelledAfter = c.ModelledAfter }),
    wahs = WahBlock.Circuits.Select(static c => new { name = c.Name, modelledAfter = c.ModelledAfter })
        .Concat(WahBlock.ActiveCircuits.Select(static c => new { name = c.Name, modelledAfter = c.ModelledAfter })),
    cab = new {
        speakers = OptionsOf(cab, "m1speaker"),
        microphones = OptionsOf(cab, "m1mic"),
        cabinets = OptionsOf(cab, "m1cab")
    }
};

var json = JsonSerializer.Serialize(catalogue, new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping });
var path = Path.Combine("src", "app", "catalog", "engine.generated.ts");

Directory.CreateDirectory(Path.GetDirectoryName(path)!);
File.WriteAllText(
    path,
    "// Generated by tools/catalog.cs from the engine's block registry: run `pnpm catalog`, do not edit.\n\n" +
    $"export const ENGINE = {json} as const;\n"
);
Console.WriteLine($"Wrote {path}");
