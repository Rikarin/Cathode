// Writes src/app/manual/content.generated.ts: an import of every block page (blocks/<typeId>.ts) and every guide
// chapter (guide/<slug>.md) that exists, so a block or chapter whose text is not written yet leaves a gap in the manual
// rather than breaking the build. `pnpm build` and `pnpm start` run it first; run it again (`node
// tools/manual-index.mjs`) after adding a file while the dev server is running.

import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const manual = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'app', 'manual');

/** The names (without extension) of the files in `dir` that end in `ext`, sorted. */
const names = (dir, ext) =>
  existsSync(join(manual, dir))
    ? readdirSync(join(manual, dir))
        .filter(file => file.endsWith(ext) && !file.endsWith('.d.ts') && file !== 'index.ts')
        .map(file => file.slice(0, -ext.length))
        .sort()
    : [];

/** A file name as a JavaScript identifier: `getting-started` → `getting_started`. */
const identifier = name => name.replace(/[^A-Za-z0-9_$]/g, '_');

export function writeIndex() {
  const blocks = names('blocks', '.ts');
  const chapters = names('guide', '.md');
  const hasChapters = existsSync(join(manual, 'guide', 'chapters.ts'));

  const lines = [
    '// Generated by tools/manual-index.mjs from the files in blocks/ and guide/: do not edit.',
    '',
    hasChapters ? "import type { BlockDoc } from './types';" : "import type { BlockDoc, Chapter } from './types';",
    '',
    ...blocks.map(name => `import { doc as block_${identifier(name)} } from './blocks/${name}';`),
    ...chapters.map(name => `import guide_${identifier(name)} from './guide/${name}.md';`),
    '',
    hasChapters
      ? "export { CHAPTERS } from './guide/chapters';"
      : '/** guide/chapters.ts is not written yet. */\nexport const CHAPTERS: readonly Chapter[] = [];',
    '',
    '/** Each block page that exists, by the block type id. */',
    'export const BLOCK_DOCS: Readonly<Record<string, BlockDoc>> = {',
    blocks.map(name => `  '${name}': block_${identifier(name)}`).join(',\n'),
    '};',
    '',
    "/** Each chapter's Markdown that exists, by its slug. */",
    'export const GUIDE_TEXT: Readonly<Record<string, string>> = {',
    chapters.map(name => `  '${name}': guide_${identifier(name)}`).join(',\n'),
    '};',
    ''
  ];

  const path = join(manual, 'content.generated.ts');
  writeFileSync(path, lines.join('\n').replace(/\{\n\n\}/g, '{}'));
  return { blocks, chapters, path };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { blocks, chapters } = writeIndex();
  console.log(`Manual: ${blocks.length} block pages, ${chapters.length} chapters.`);
}
