using System.Diagnostics;
using System.Globalization;
using System.Text;
using Cathode.Dsp;
using Cathode.Dsp.Parameters;

// Measures each registered block at 48 kHz in 64-frame blocks on noise, as a percentage of one core in real time:
// the default settings, and the worst of each value of the block's type/mode choice (for the Cab, slot 1's Source).
// With --write it regenerates src/Cathode.Dsp/BlockCosts.cs, which the catalog serves to the editor's CPU estimate
// (docs/03 §12). --only <typeId> measures one block (and never writes). --amps times Circuit Amp models one by one (see
// MeasureAmps).
const double Rate = 48_000;
const int Frames = 64;
const int Blocks = 8_000; // about 10.7 s of audio per measurement

// Blocks that convolve are measured with the longest IR they keep: a noise IR long enough for any of them.
var irPath = Path.Combine(Path.GetTempPath(), "cathode-bench-ir.wav");
var noise = new Random(7);
Cathode.Dsp.IO.WavFile.Write(
    irPath,
    new((int)Rate, [Enumerable.Range(0, 32_768).Select(_ => (float)(noise.NextDouble() - 0.5)).ToArray()])
);

var registry = BlockRegistry.CreateDefault();
var results = new SortedDictionary<string, double>(StringComparer.Ordinal);
var onlyAt = Array.IndexOf(args, "--only");
var only = onlyAt >= 0 && onlyAt + 1 < args.Length ? args[onlyAt + 1] : null;
var ampsAt = Array.IndexOf(args, "--amps");
if (ampsAt >= 0) {
    return MeasureAmps(args[(ampsAt + 1)..]);
}

foreach (var descriptor in registry.Descriptors.Where(d => only is null || d.TypeId == only)) {
    var variants = descriptor.Params
        .Select((p, i) => (p, i))
        .FirstOrDefault(static x => x.p.Kind == ParamKind.Enum && x.p.Id is "type" or "mode" or "model" or "m1source");
    var worst = Measure(registry, descriptor.TypeId, -1, 0, irPath);
    if (variants.p is { } choice) {
        for (var option = 0; option <= (int)choice.Max; option++) {
            worst = Math.Max(worst, Measure(registry, descriptor.TypeId, variants.i, option, irPath));
        }
    }

    results[descriptor.TypeId] = worst;
    Console.WriteLine($"{descriptor.TypeId,-12} {worst,6:0.00} %");
}

// The Cab's IR synthesis and mixing run on the control thread, so they are not part of its audio cost: report them apart.
using (var cab = new Cathode.Dsp.Blocks.CabBlock()) {
    cab.Prepare(new(Rate, Frames));
    var position = Cathode.Dsp.Blocks.CabBlock.SlotParam(0, Cathode.Dsp.Blocks.CabBlock.Position);
    var level = Cathode.Dsp.Blocks.CabBlock.SlotParam(0, Cathode.Dsp.Blocks.CabBlock.SlotLevel);

    double Time(int param, int runs) {
        var start = Stopwatch.GetTimestamp();
        for (var i = 0; i < runs; i++) {
            cab.Params.SetTarget(param, i % 2 == 0 ? 10f : 20f);
            cab.Refresh();
        }

        return Stopwatch.GetElapsedTime(start).TotalMilliseconds / runs;
    }

    Time(position, 20); // warm up
    Console.WriteLine(
        $"cab IR synthesis (one slot moved, control thread): {Time(position, 100):0.00} ms; remix only (a level): {Time(level, 100):0.00} ms"
    );
}

if (args.Contains("--write") && only is null) {
    var path = Path.Combine(FindEngineRoot(), "src", "Cathode.Dsp", "BlockCosts.cs");
    var code = new StringBuilder();
    code.AppendLine("namespace Cathode.Dsp;");
    code.AppendLine();
    code.AppendLine("/// <summary>");
    code.AppendLine(
        "///     Measured CPU cost of each block type, in percent of one core at 48 kHz (64-frame blocks, worst type, longest"
    );
    code.AppendLine("///     IRs; an amp's cost depends on its model and is measured without one), on the");
    code.AppendLine(
        CultureInfo.InvariantCulture,
        $"///     reference machine ({System.Runtime.InteropServices.RuntimeInformation.OSDescription.Trim()}, {System.Runtime.InteropServices.RuntimeInformation.ProcessArchitecture}). Generated by"
    );
    code.AppendLine(
        "///     <c>dotnet run -c Release --project tools/Cathode.Bench -- --write</c>; rerun it after adding or changing a block."
    );
    code.AppendLine("/// </summary>");
    code.AppendLine("public static class BlockCosts {");
    code.AppendLine("    static readonly Dictionary<string, double> Percent = new(StringComparer.Ordinal) {");
    var lines = results.Select(r => $"        [\"{r.Key}\"] = {r.Value.ToString("0.00", CultureInfo.InvariantCulture)}")
        .ToList();
    code.AppendLine(string.Join(",\n", lines));
    code.AppendLine("    };");
    code.AppendLine();
    code.AppendLine(
        """    /// <summary>The cost of <paramref name="typeId" />, or null for a block that has not been measured.</summary>"""
    );
    code.AppendLine(
        "    public static double? Of(string typeId) => Percent.TryGetValue(typeId, out var cost) ? cost : null;"
    );
    code.AppendLine("}");
    File.WriteAllText(path, code.ToString());
    Console.WriteLine($"wrote {path}");
}

return 0;

static double Measure(BlockRegistry registry, string typeId, int param, int value, string irPath) {
    using var block = registry.Create(typeId);
    if (param >= 0) {
        block.Params.SetTarget(param, value);
    }

    if (block is IAssetConsumer consumer) {
        foreach (var slot in consumer.AssetSlots.Where(static s => s != "model")) {
            consumer.LoadAsset(slot, irPath);
        }
    }

    block.Prepare(new(Rate, Frames));
    var left = new float[Frames];
    var right = new float[Frames];
    var random = new Random(1);
    var context = new BlockContext(Rate, 120, 0);
    var best = double.MaxValue;
    for (var run = 0; run < 3; run++) {
        var start = Stopwatch.GetTimestamp();
        for (var b = 0; b < Blocks; b++) {
            for (var i = 0; i < Frames; i++) {
                left[i] = (float)(random.NextDouble() - 0.5) * 0.5f;
                right[i] = left[i];
            }

            block.Process(new(left, right), context);
        }

        best = Math.Min(best, Stopwatch.GetElapsedTime(start).TotalSeconds);
    }

    return 100 * best / (Blocks * Frames / Rate);
}

// --amps [model ...] [--set index=value ...]: each Circuit Amp model (all of them without names) on a strummed chord and
// on loud noise, as a percentage of one core, with the Plexi measured in the same passes as a yardstick. Each figure is
// the best of five passes taken in turn, timed in process CPU time, so a loaded machine distorts it less than wall time.
static int MeasureAmps(string[] args) {
    const int Passes = 5;
    const int AmpBlocks = 4_000; // about 5.3 s of audio per measurement
    var names = args.TakeWhile(static a => !a.StartsWith("--", StringComparison.Ordinal)).ToList();
    var settings = new List<(int Index, float Value)>();
    for (var i = 0; i + 1 < args.Length; i++) {
        if (args[i] == "--set" && args[i + 1].Split('=') is [var index, var value]) {
            settings.Add(
                (int.Parse(index, CultureInfo.InvariantCulture), float.Parse(value, CultureInfo.InvariantCulture))
            );
        }
    }

    var designs = Cathode.Dsp.Amp.AmpDesign.All.Select(static a => a.Name).ToList();
    if (names.Count == 0) {
        names = designs;
    }

    names = ["Plexi", ..names.Where(static n => n != "Plexi")];
    var guitar = Signal(true);
    var noise = Signal(false);
    var best = names.ToDictionary(static n => n, static _ => (Guitar: double.MaxValue, Noise: double.MaxValue));
    for (var pass = 0; pass < Passes; pass++) {
        foreach (var name in names) {
            var type = designs.IndexOf(name);
            if (type < 0) {
                throw new ArgumentException($"No Circuit Amp model is called \"{name}\".");
            }

            var (g, n) = best[name];
            best[name] = (Math.Min(g, Run(type, guitar)), Math.Min(n, Run(type, noise)));
        }
    }

    var plexi = best["Plexi"];
    foreach (var name in names) {
        var (g, n) = best[name];
        Console.WriteLine(
            $"{name,-22} guitar {g,5:0.0} % ({g / plexi.Guitar:0.00} × Plexi)  noise {n,5:0.0} % ({n / plexi.Noise:0.00} × Plexi)"
        );
    }

    return 0;

    double Run(int type, float[] signal) {
        using var block = new Cathode.Dsp.Blocks.CircuitAmpBlock();
        block.Params.SetTarget(Cathode.Dsp.Blocks.CircuitAmpBlock.Type, type);
        foreach (var (index, value) in settings) {
            block.Params.SetTarget(index, value);
        }

        block.Prepare(new(Rate, Frames));
        var left = new float[Frames];
        var right = new float[Frames];
        var context = new BlockContext(Rate, 120, 0);
        block.Process(new(left, right), context); // warm up
        var process = Process.GetCurrentProcess();
        var start = process.TotalProcessorTime;
        for (var b = 0; b < AmpBlocks; b++) {
            signal.AsSpan(b * Frames, Frames).CopyTo(left);
            left.CopyTo(right);
            block.Process(new(left, right), context);
        }

        process.Refresh();
        return 100 * (process.TotalProcessorTime - start).TotalSeconds / (AmpBlocks * Frames / Rate);
    }

    // A chord strummed every half second (decaying partials about 0.3 peak, with pick noise), or uniform noise ±0.25.
    static float[] Signal(bool chord) {
        double[] notes = [82.4, 123.5, 164.8, 207.7, 246.9, 329.6];
        var random = new Random(1);
        var y = new float[AmpBlocks * Frames];
        for (var n = 0; n < y.Length; n++) {
            if (!chord) {
                y[n] = (float)(random.NextDouble() - 0.5) * 0.5f;
                continue;
            }

            var t = n % 24_000 / Rate;
            var s = 0.0;
            foreach (var f in notes) {
                s += Math.Sin(2 * Math.PI * f * n / Rate) + 0.3 * Math.Sin(4 * Math.PI * f * n / Rate);
            }

            y[n] = (float)(0.05 * Math.Exp(-t * 4) * s + (t < 0.005 ? (random.NextDouble() - 0.5) * 0.2 : 0));
        }

        return y;
    }
}

static string FindEngineRoot() {
    var directory = new DirectoryInfo(AppContext.BaseDirectory);
    while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Cathode.slnx"))) {
        directory = directory.Parent;
    }

    return directory?.FullName ?? throw new InvalidOperationException("Run from inside the engine folder.");
}
