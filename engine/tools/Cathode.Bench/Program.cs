using System.Diagnostics;
using System.Globalization;
using System.Text;
using Cathode.Dsp;
using Cathode.Dsp.Parameters;

// Measures each registered block at 48 kHz in 64-frame blocks on noise, as a percentage of one core in real time:
// the default settings, and the worst of each value of the block's type/mode choice. With --write it regenerates
// src/Cathode.Dsp/BlockCosts.cs, which the catalog serves to the editor's CPU estimate (docs/03 §12).
const double Rate = 48_000;
const int Frames = 64;
const int Blocks = 8_000; // about 10.7 s of audio per measurement

// Blocks that convolve are measured with the longest IR they keep: a noise IR long enough for any of them.
var irPath = Path.Combine(Path.GetTempPath(), "cathode-bench-ir.wav");
var noise = new Random(7);
Cathode.Dsp.IO.WavFile.Write(
    irPath,
    new((int)Rate, [Enumerable.Range(0, 32_768).Select(_ => (float)(noise.NextDouble() - 0.5)).ToArray()])
);

var registry = BlockRegistry.CreateDefault();
var results = new SortedDictionary<string, double>(StringComparer.Ordinal);
foreach (var descriptor in registry.Descriptors) {
    var variants = descriptor.Params
        .Select((p, i) => (p, i))
        .FirstOrDefault(static x => x.p.Kind == ParamKind.Enum && x.p.Id is "type" or "mode" or "model");
    var worst = Measure(registry, descriptor.TypeId, -1, 0, irPath);
    if (variants.p is { } choice) {
        for (var option = 0; option <= (int)choice.Max; option++) {
            worst = Math.Max(worst, Measure(registry, descriptor.TypeId, variants.i, option, irPath));
        }
    }

    results[descriptor.TypeId] = worst;
    Console.WriteLine($"{descriptor.TypeId,-12} {worst,6:0.00} %");
}

// DynaCab's IR synthesis runs on the control thread, so it is not part of the block's audio cost: report it apart.
using (var cab = new Cathode.Dsp.Blocks.DynaCabBlock()) {
    cab.Prepare(new(Rate, Frames));
    var position = Cathode.Dsp.Blocks.DynaCabBlock.SlotParam(0, Cathode.Dsp.Blocks.DynaCabBlock.Position);
    var level = Cathode.Dsp.Blocks.DynaCabBlock.SlotParam(0, Cathode.Dsp.Blocks.DynaCabBlock.SlotLevel);
    double Time(int param, int runs) {
        var start = Stopwatch.GetTimestamp();
        for (var i = 0; i < runs; i++) {
            cab.Params.SetTarget(param, i % 2 == 0 ? 10f : 20f);
            cab.Refresh();
        }

        return Stopwatch.GetElapsedTime(start).TotalMilliseconds / runs;
    }

    Time(position, 20); // warm up
    Console.WriteLine($"dynacab IR synthesis (one slot moved, control thread): {Time(position, 100):0.00} ms; remix only (a level): {Time(level, 100):0.00} ms");
}

if (args.Contains("--write")) {
    var path = Path.Combine(FindEngineRoot(), "src", "Cathode.Dsp", "BlockCosts.cs");
    var code = new StringBuilder();
    code.AppendLine("namespace Cathode.Dsp;");
    code.AppendLine();
    code.AppendLine("/// <summary>");
    code.AppendLine("///     Measured CPU cost of each block type, in percent of one core at 48 kHz (64-frame blocks, worst type, longest");
    code.AppendLine("///     IRs; an amp's cost depends on its model and is measured without one), on the");
    code.AppendLine(CultureInfo.InvariantCulture, $"///     reference machine ({System.Runtime.InteropServices.RuntimeInformation.OSDescription.Trim()}, {System.Runtime.InteropServices.RuntimeInformation.ProcessArchitecture}). Generated by");
    code.AppendLine("///     <c>dotnet run -c Release --project tools/Cathode.Bench -- --write</c>; rerun it after adding or changing a block.");
    code.AppendLine("/// </summary>");
    code.AppendLine("public static class BlockCosts {");
    code.AppendLine("    static readonly Dictionary<string, double> Percent = new(StringComparer.Ordinal) {");
    var lines = results.Select(r => $"        [\"{r.Key}\"] = {r.Value.ToString("0.00", CultureInfo.InvariantCulture)}").ToList();
    code.AppendLine(string.Join(",\n", lines));
    code.AppendLine("    };");
    code.AppendLine();
    code.AppendLine("    /// <summary>The cost of <paramref name=\"typeId\" />, or null for a block that has not been measured.</summary>");
    code.AppendLine("    public static double? Of(string typeId) => Percent.TryGetValue(typeId, out var cost) ? cost : null;");
    code.AppendLine("}");
    File.WriteAllText(path, code.ToString());
    Console.WriteLine($"wrote {path}");
}

return 0;

static double Measure(BlockRegistry registry, string typeId, int param, int value, string irPath) {
    using var block = registry.Create(typeId);
    if (param >= 0) {
        block.Params.SetTarget(param, value);
    }

    if (block is IAssetConsumer consumer) {
        foreach (var slot in consumer.AssetSlots.Where(static s => s != "model")) {
            consumer.LoadAsset(slot, irPath);
        }
    }

    block.Prepare(new(Rate, Frames));
    var left = new float[Frames];
    var right = new float[Frames];
    var random = new Random(1);
    var context = new BlockContext(Rate, 120, 0);
    var best = double.MaxValue;
    for (var run = 0; run < 3; run++) {
        var start = Stopwatch.GetTimestamp();
        for (var b = 0; b < Blocks; b++) {
            for (var i = 0; i < Frames; i++) {
                left[i] = (float)(random.NextDouble() - 0.5) * 0.5f;
                right[i] = left[i];
            }

            block.Process(new(left, right), context);
        }

        best = Math.Min(best, Stopwatch.GetElapsedTime(start).TotalSeconds);
    }

    return 100 * best / (Blocks * Frames / Rate);
}

static string FindEngineRoot() {
    var directory = new DirectoryInfo(AppContext.BaseDirectory);
    while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Cathode.slnx"))) {
        directory = directory.Parent;
    }

    return directory?.FullName ?? throw new InvalidOperationException("Run from inside the engine folder.");
}
